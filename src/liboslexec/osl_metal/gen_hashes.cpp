// Writes OSL::Hashes, the hashes of the strings in strdecls.h, as an msl
// header. osl computes them at compile time with farmhash, which the metal
// runtime doesn't have, so they're computed here instead.
//
//   gen_hashes <output header>

#include <OSL/hashes.h>

#include <cstdio>
#include <cstring>

// Names msl reserves, which a Hashes entry can't use as is. metalize.json
// renames the references to match.
static const char*
msl_safe(const char* name)
{
    static const char* reserved[] = { "constant", "device", "thread",
                                      "threadgroup", "kernel", "vertex",
                                      "fragment", "sampler" };
    static char buf[256];
    for (const char* r : reserved)
        if (!std::strcmp(name, r)) {
            std::snprintf(buf, sizeof buf, "%s_", name);
            return buf;
        }
    return name;
}

int
main(int argc, char** argv)
{
    if (argc < 2)
        return 2;
    FILE* f = std::fopen(argv[1], "w");
    if (!f)
        return 1;
    std::fprintf(f, "// Generated by gen_hashes from OSL/strdecls.h. Do not edit.\n"
                    "#pragma once\n\nOSL_NAMESPACE_BEGIN\nnamespace Hashes {\n");
#define STRDECL(str, var_name)                                                   \
    std::fprintf(f, "constant constexpr ustringhash %s = { 0x%016llxull };\n", msl_safe(#var_name), \
                 (unsigned long long)OSL::strhash(str));
#include <OSL/strdecls.h>
#undef STRDECL
    std::fprintf(f, "}  // namespace Hashes\nOSL_NAMESPACE_END\n");
    std::fclose(f);
    return 0;
}
